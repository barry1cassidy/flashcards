/**
 * Extra decks for existing library groups, plus new subject catalogs.
 * Run: node scripts/build-library-expansions.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'main', 'resources', 'library')

function card(front, back, hint = '') {
  return hint ? { front, back, hint } : { front, back }
}

function deck(slug, name, description, cards) {
  return { slug, name, description, position: 0, cards }
}

function group(meta, decks) {
  return {
    groups: [
      {
        ...meta,
        sourceLanguage: 'en-US',
        targetLanguage: 'en-US',
        decks: decks.map((d, i) => ({ ...d, position: i })),
      },
    ],
  }
}

function write(file, data) {
  writeFileSync(join(outDir, file), `${JSON.stringify(data, null, 2)}\n`)
  const g = data.groups[0]
  const cards = g.decks.reduce((n, d) => n + d.cards.length, 0)
  console.log(`${file}: ${g.decks.length} decks, ${cards} cards`)
}

function pairs(list) {
  return list.map(([front, back, hint]) => (hint ? card(front, back, hint) : card(front, back)))
}

