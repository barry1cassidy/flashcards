function timesDeck(slug, name, description, factors) {
  const cards = []
  for (const a of factors) {
    for (let b = 1; b <= 12; b += 1) {
      cards.push(card(`${a} × ${b}`, String(a * b)))
    }
  }
  return deck(slug, name, description, cards)
}

