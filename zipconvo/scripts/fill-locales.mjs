const zdEn = flat(JSON.parse(fs.readFileSync(path.join(zipdeckDir, 'en.json'), 'utf8')))
const byEnglish = {}
for (const [key, value] of Object.entries(zdEn)) {
  if (typeof value === 'string' && byEnglish[value] === undefined) byEnglish[value] = key
}

for (const file of fs.readdirSync(dir)) {
  if (!file.endsWith('.json') || file === 'en.json') continue
  const code = file.replace('.json', '')
  const data = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'))
  const have = new Set(Object.keys(flat(data)))
  const zd = flat(JSON.parse(fs.readFileSync(path.join(zipdeckDir, file), 'utf8')))
  const pack = added[code] || {}
  for (const key of Object.keys(en)) {
    if (have.has(key)) continue
    const english = en[key]
    const harvested = byEnglish[english] ? zd[byEnglish[english]] : undefined
    const value = harvested || pack[key]
    if (typeof value !== 'string') throw new Error(`Missing translation ${code} ${key}`)
    const placeholders = english.match(/\{\{[^}]+\}\}/g) || []
    for (const token of placeholders) {
      if (!value.includes(token)) throw new Error(`Placeholder ${token} missing in ${code} ${key}`)
    }
    setPath(data, key, value)
  }
  fs.writeFileSync(path.join(dir, file), `${JSON.stringify(data, null, 2)}\n`)
  console.log('updated', file)
}
